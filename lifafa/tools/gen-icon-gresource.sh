#!/usr/bin/env bash
#
# Regenerate the symbolic-icon set embedded in the Hylki binary.
#
# Hylki draws every icon from this bundle, never from the user's icon theme,
# so it looks the same on every desktop (register_icons in
# src/desktop/icon_theme.rs). The embedded GResource (see build.rs + src/main.rs
# register_resources) sits under the app's resource path, which GTK searches
# as part of hicolor, ahead of GTK's and libadwaita's own built-in copies.
#
# Run this after adding/removing an icon reference in the source, and after
# the build machine's GTK, libadwaita or Adwaita icons change. It:
#   1. scans src/ for every "<name>-symbolic" string, and GTK and libadwaita
#      (their code, stylesheets and UI files) for every icon they name,
#   2. copies each one's SVG from Hylki's own icons (data/icons/hicolor/
#      symbolic/actions, all of which are bundled), from Adwaita, or from
#      libadwaita's or GTK's built-in resources,
#   3. rewrites resources/hylki.gresource.xml to list exactly those files.
#
# An icon whose name is built at run time has to appear somewhere in full as
# well, or step 1 cannot see it. A name GTK or libadwaita mentions but no
# source has is not an icon they draw (a style asset, a stray string), and is
# left out; one Hylki names is an error.
#
# Requires: the adwaita-icon-theme package installed (for /usr/share/icons/Adwaita).
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
DST="$ROOT/resources/icons/scalable/actions"
APPS_DST="$ROOT/resources/icons/scalable/apps"
CUSTOM="$ROOT/data/icons/hicolor/symbolic/actions"   # Hylki's own SVGs
APPS="$ROOT/data/icons/hicolor/scalable/apps"         # the app's own icon
ADWAITA="/usr/share/icons/Adwaita"
ADW_LIB="$(ldconfig -p | grep -om1 '/[^ ]*libadwaita[^ ]*\.so[^ ]*' || true)"
GTK_LIB="$(ldconfig -p | grep -om1 '/[^ ]*libgtk-4\.so[^ ]*' || true)"

# Names referenced in the code, and every icon of Hylki's own.
mapfile -t names < <(
    {
        grep -rhoE '"[a-z0-9-]+-symbolic"' "$ROOT/src" | tr -d '"'
        for f in "$CUSTOM"/*.svg; do basename "$f" .svg; done
    } | sort -u
)

# Names GTK and libadwaita draw for their own widgets.
mapfile -t toolkit < <(
    for lib in "$GTK_LIB" "$ADW_LIB"; do
        [ -n "$lib" ] || continue
        strings "$lib"
        for r in $(gresource list "$lib" | grep -E '\.(css|ui)$'); do
            gresource extract "$lib" "$r"
        done
    done | grep -oE '[a-z][a-z0-9-]*-symbolic' | sort -u
)
if [ ${#toolkit[@]} -eq 0 ]; then
    echo "!! Found no icons named by GTK or libadwaita; are they installed?" >&2
    exit 1
fi

echo "==> ${#names[@]} icons referenced in src/ or drawn for Hylki, ${#toolkit[@]} names in GTK and libadwaita"
rm -rf "$DST"
mkdir -p "$DST"

# Copy one icon into the bundle; fails when no source has it.
fetch() {
    local n=$1 out="$DST/$1.svg" f
    if   [ -f "$CUSTOM/$n.svg" ]; then
        cp "$CUSTOM/$n.svg" "$out"
    elif f=$(find "$ADWAITA" -name "$n.svg" 2>/dev/null | head -1) && [ -n "$f" ]; then
        cp "$f" "$out"
    elif [ -n "$ADW_LIB" ] && gresource extract "$ADW_LIB" \
            "/org/gnome/Adwaita/icons/scalable/actions/$n.svg" > "$out" 2>/dev/null \
            && [ -s "$out" ]; then
        :  # libadwaita's internal resources (e.g. adw-external-link)
    elif [ -n "$GTK_LIB" ] && gresource extract "$GTK_LIB" \
            "/org/gtk/libgtk/icons/$n.svg" > "$out" 2>/dev/null \
            && [ -s "$out" ]; then
        :  # GTK's internal resources
    else
        rm -f "$out"
        return 1
    fi
}

missing=()
for n in "${names[@]}"; do
    fetch "$n" || missing+=("$n")
done
for n in "${toolkit[@]}"; do
    [ -f "$DST/$n.svg" ] || fetch "$n" || true
done

# The app's own icon too: the window and About find it by name, and with
# the icon folders on disk left out of the search (register_icons), only
# the bundle can answer.
rm -rf "$APPS_DST"
mkdir -p "$APPS_DST"
cp "$APPS"/*.svg "$APPS_DST"/

if [ ${#missing[@]} -gt 0 ]; then
    echo "!! Could not source: ${missing[*]}" >&2
    echo "   Add an SVG to $CUSTOM/ and re-run." >&2
    exit 1
fi

# Rewrite the gresource manifest.
{
    echo '<?xml version="1.0" encoding="UTF-8"?>'
    echo '<!-- Auto-generated by tools/gen-icon-gresource.sh; do not edit by hand.'
    echo '     Every symbolic icon Hylki, GTK and libadwaita name, as found on the'
    echo '     build machine: Hylki draws them all from here, never from the'
    echo '     user'"'"'s icon theme. Embedded in the binary via build.rs. -->'
    echo '<gresources>'
    echo '  <gresource prefix="/co/hyprlab/Hylki">'
    for f in $(cd "$DST" && ls *.svg | sort); do
        echo "    <file>icons/scalable/actions/$f</file>"
    done
    for f in $(cd "$APPS_DST" && ls *.svg | sort); do
        echo "    <file>icons/scalable/apps/$f</file>"
    done
    echo '  </gresource>'
    echo '</gresources>'
} > "$ROOT/resources/hylki.gresource.xml"

echo "==> Bundled $(ls "$DST" | wc -l) icons; wrote resources/hylki.gresource.xml"
